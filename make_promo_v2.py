"""Promo card v2 for Sound-Out Speller — Pillow, 1200x630, code-drawn only.
Updated for the C2-AFFR default model (2026-11-20). Examples shown
(wos->was, teh->the, jress->dress) are verified top-1 outputs of the
C2-AFFR runtime path (features_phase1.pair_features_ext + S2 lookup,
checked 2026-11-20). Stats: fresh generated exam 95.38% top-1, frozen
1,000-word vocabulary, model_c2.npz 6,767 bytes, 0 correct words changed.
Pattern follows make_promo.py (v1 card)."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
W, H = 1200, 630
BG = (253, 246, 236)
INK = (45, 42, 38)
MUTED = (122, 114, 103)
ACCENT = (232, 106, 78)
CARD = (255, 255, 255)
CHIP = (253, 238, 218)

img = Image.new("RGB", (W, H), BG)
d = ImageDraw.Draw(img)


def font(size, bold=False):
    path = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
    return ImageFont.truetype(path, size)


d.rounded_rectangle([40, 40, W - 40, H - 40], radius=36, fill=CARD, outline=(231, 220, 200), width=3)
d.text((90, 78), "Sound-Out Speller", font=font(76, True), fill=INK)
d.text((92, 172), "Hear it. Sound it out. Spell it.", font=font(36), fill=MUTED)

# example pills — verified C2-AFFR top-1 outputs
examples = [("wos", "was"), ("teh", "the"), ("jress", "dress")]
x = 90
for att, tgt in examples:
    label = f"{att}  ->  {tgt}"
    f = font(34, True)
    tw = d.textlength(label, font=f)
    d.rounded_rectangle([x, 248, x + tw + 44, 248 + 66], radius=33, fill=CHIP)
    d.text((x + 22, 248 + 14), label, font=f, fill=INK)
    x += tw + 44 + 22

stats = [
    ("95.4%", "right word first*"),
    ("1,000", "words"),
    ("6.7 KB", "model, fully offline"),
    ("0", "correct words changed"),
]
x = 90
for big, small in stats:
    d.text((x, 372), big, font=font(52, True), fill=ACCENT)
    d.text((x, 436), small, font=font(21), fill=MUTED)
    x += 248

d.text((90, 478), "*On a fresh code-generated exam (1,754 attempts) - see README for real-data scores.",
       font=font(20), fill=MUTED)
d.text((90, 520), "A tiny model for early spellers - runs on the device, nothing leaves it.",
       font=font(27), fill=INK)
d.text((90, 560), "Training data generated by code. No child's writing, no AI-generated training data.",
       font=font(22), fill=MUTED)

out = HERE / "promo" / "sound-out-speller-promo-v2.png"
out.parent.mkdir(exist_ok=True)
img.save(out)
print(f"wrote {out}")
